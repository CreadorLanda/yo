/**
 * Truth or Dare — the game engine.
 *
 * Runs 100% client-side on every participant's device. Messages of
 * message_type 'game' carry a JSON payload with the event stream; each
 * device replays that stream to derive the same game state. There is no
 * server state and the payload is end-to-end encrypted like any other
 * message.
 *
 * Deterministic roulette: the round's current player is derived from
 * (seed, round, memberIds), so every device picks the same person without
 * anyone "holding the wheel".
 */

export type GameKind = 'truth-or-dare';

/** The single game message shape, serialised into the E2EE body. */
export type GameMessagePayload =
  | {
      kind: 'game';
      game: 'truth-or-dare';
      action: 'start';
      seed: string;
      maxRounds: number;
      playerId?: string;
      playerIds?: string[];
    }
  | { kind: 'game'; game: 'truth-or-dare'; action: 'join'; playerId: string }
  | { kind: 'game'; game: 'truth-or-dare'; action: 'choose'; playerId: string; choice: 'truth' | 'dare' }
  | { kind: 'game'; game: 'truth-or-dare'; action: 'challenge'; playerId: string; text: string }
  | { kind: 'game'; game: 'truth-or-dare'; action: 'done'; playerId: string }
  | { kind: 'game'; game: 'truth-or-dare'; action: 'end'; winnerId?: string };

export type TruthOrDareChoice = 'truth' | 'dare';

export interface TruthOrDareState {
  active: boolean;
  seed: string;
  maxRounds: number;
  round: number;
  /** Index into memberIds — the player whose turn it is. */
  currentIndex: number | null;
  currentPlayerId: string | null;
  choice: TruthOrDareChoice | null;
  /** Challenge text written by another member, pending resolution. */
  challenge: string | null;
  challengeBy: string | null;
  /**
   * Players who have completed a turn. Not reset per round: with one player
   * per round it reads as "has had a go", which is what the room's tiles
   * show against each name.
   */
  doneIds: string[];
  /** Rounds each player completed (for scoreboard). */
  scoreboard: Record<string, number>;
  ended: boolean;
  winnerId: string | null;
  /** Frozen roster for this stream. Channels build it through join events. */
  playerIds: string[];
}

export const MAX_ROUNDS = 5;

/** Pure, stable hash — must match across devices. */
function hashString(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/**
 * Deterministic player pick for a round.
 * `memberIds` must be sorted so every device orders the same way.
 */
export function pickPlayer(seed: string, round: number, memberIds: string[]): number {
  if (memberIds.length === 0) return -1;
  const h = hashString(`${seed}:${round}`);
  return h % memberIds.length;
}

/**
 * The next round's player, avoiding an immediate repeat.
 *
 * A wheel that lands on the same person twice in a row reads as broken even
 * when it is honest chance. Stepping to the neighbour keeps every device in
 * agreement, because the rule is as deterministic as the pick it corrects.
 */
export function nextPlayer(
  seed: string,
  round: number,
  memberIds: string[],
  previousId: string | null,
): number {
  if (memberIds.length === 0) return -1;
  const idx = pickPlayer(seed, round, memberIds);
  if (memberIds.length > 1 && memberIds[idx] === previousId) {
    return (idx + 1) % memberIds.length;
  }
  return idx;
}

/** Initial state for a fresh game. */
export function emptyState(): TruthOrDareState {
  return {
    active: false,
    seed: '',
    maxRounds: MAX_ROUNDS,
    round: 1,
    currentIndex: null,
    currentPlayerId: null,
    choice: null,
    challenge: null,
    challengeBy: null,
    doneIds: [],
    scoreboard: {},
    ended: false,
    winnerId: null,
    playerIds: [],
  };
}

/** Random seed, generated by the player who starts the game. */
export function newSeed(): string {
  const bytes = new Uint8Array(16);
  const webCrypto = globalThis.crypto;
  if (webCrypto?.getRandomValues) {
    webCrypto.getRandomValues(bytes);
  } else {
    // Hermes does not expose Web Crypto in this build. Keep the native
    // dependency out of the pure game engine's test graph.
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    const nativeCrypto = require('expo-crypto') as {
      getRandomBytes(length: number): Uint8Array;
    };
    bytes.set(nativeCrypto.getRandomBytes(bytes.length));
  }
  return Array.from(bytes)
    .map((b) => b.toString(16).padStart(2, '0'))
    .join('');
}

/**
 * Replay the game event stream (all messages of type 'game' in a chat,
 * oldest first) into the current state.
 *
 * @param payloads      parsed game payloads, chronological
 * @param memberIds     member ids, SORTED — drives deterministic picks
 */
export function replayGame(payloads: GameMessagePayload[], memberIds: string[]): TruthOrDareState {
  const state = emptyState();

  for (const p of payloads) {
    switch (p.action) {
      case 'start': {
        state.active = true;
        state.seed = p.seed;
        state.maxRounds = p.maxRounds;
        state.round = 1;
        state.doneIds = [];
        state.scoreboard = {};
        state.choice = null;
        state.challenge = null;
        state.challengeBy = null;
        state.ended = false;
        state.winnerId = null;
        state.playerIds = sortedMemberIds(
          (p.playerIds?.length ? p.playerIds : memberIds).filter(Boolean),
        );
        if (p.playerId && !state.playerIds.includes(p.playerId)) {
          state.playerIds = sortedMemberIds([...state.playerIds, p.playerId]);
        }
        const idx = state.playerIds.length >= 2
          ? pickPlayer(state.seed, 1, state.playerIds)
          : -1;
        state.currentIndex = idx;
        state.currentPlayerId = idx >= 0 ? state.playerIds[idx] : null;
        break;
      }
      case 'join': {
        if (!state.active || state.ended || state.currentPlayerId || !p.playerId) break;
        if (!state.playerIds.includes(p.playerId)) {
          state.playerIds = sortedMemberIds([...state.playerIds, p.playerId]);
        }
        if (state.playerIds.length >= 2) {
          const idx = pickPlayer(state.seed, 1, state.playerIds);
          state.currentIndex = idx;
          state.currentPlayerId = state.playerIds[idx] ?? null;
        }
        break;
      }
      case 'choose': {
        if (!state.active || state.ended || p.playerId !== state.currentPlayerId || state.choice) break;
        state.choice = p.choice;
        state.challenge = null;
        state.challengeBy = null;
        break;
      }
      case 'challenge': {
        if (
          !state.active ||
          state.ended ||
          !state.choice ||
          state.challenge ||
          p.playerId === state.currentPlayerId ||
          !state.playerIds.includes(p.playerId)
        ) break;
        state.challenge = p.text;
        state.challengeBy = p.playerId;
        break;
      }
      case 'done': {
        // The round belongs to one player, and it ends when that player is
        // done. It used to wait for every member to mark done — but the room
        // only offers the button to whoever's turn it is, so the events that
        // condition needed could never arrive. One player finished, nothing
        // advanced, and the same name stayed on the wheel forever.
        if (!state.active || state.ended) break;
        if (p.playerId !== state.currentPlayerId) break;

        // A second tap used to add a second point, so the winner was whoever
        // pressed hardest. The turn check above is what stops that now: the
        // round advances on the first `done`, so a repeat no longer matches
        // the current player. Deduping on doneIds instead would have been
        // wrong in the other direction — the wheel can land on the same
        // person again later, and that turn deserves its point.
        if (!state.doneIds.includes(p.playerId)) state.doneIds.push(p.playerId);
        state.scoreboard[p.playerId] = (state.scoreboard[p.playerId] ?? 0) + 1;

        if (state.round >= state.maxRounds) {
          state.ended = true;
          const sorted = Object.entries(state.scoreboard).sort((a, b) => b[1] - a[1]);
          state.winnerId = sorted.length > 0 ? sorted[0][0] : null;
          state.currentPlayerId = null;
          state.currentIndex = null;
          break;
        }

        state.round += 1;
        state.choice = null;
        state.challenge = null;
        state.challengeBy = null;
        const idx = nextPlayer(state.seed, state.round, state.playerIds, state.currentPlayerId);
        state.currentIndex = idx;
        state.currentPlayerId = idx >= 0 ? state.playerIds[idx] : null;
        break;
      }
      case 'end': {
        state.ended = true;
        state.winnerId = p.winnerId ?? null;
        state.currentPlayerId = null;
        state.currentIndex = null;
        break;
      }
    }
  }

  return state;
}

/** Collect chronological game payloads from a list of raw messages. */
export function extractGamePayloads(
  messages: { attachment?: { kind: string } | null }[],
): GameMessagePayload[] {
  const out: GameMessagePayload[] = [];
  for (const m of messages) {
    const a = m.attachment;
    if (a && a.kind === 'game') {
      const p = a as unknown as GameMessagePayload;
      const parsed = parseGamePayload(p);
      if (parsed) out.push(parsed);
    }
  }
  return out;
}

/** Parse persisted channel payloads without trusting their JSON shape. */
export function parseGamePayload(value: unknown): GameMessagePayload | null {
  if (!value || typeof value !== 'object') return null;
  const p = value as Record<string, unknown>;
  if (p.kind !== 'game' || p.game !== 'truth-or-dare' || typeof p.action !== 'string') {
    return null;
  }
  if (p.action === 'start') {
    if (typeof p.seed !== 'string' || !p.seed || typeof p.maxRounds !== 'number') return null;
    return {
      kind: 'game',
      game: 'truth-or-dare',
      action: 'start',
      seed: p.seed,
      maxRounds: p.maxRounds,
      ...(typeof p.playerId === 'string' ? { playerId: p.playerId } : {}),
      ...(Array.isArray(p.playerIds)
        ? { playerIds: p.playerIds.filter((id): id is string => typeof id === 'string') }
        : {}),
    };
  }
  if (p.action === 'join' || p.action === 'choose' || p.action === 'challenge' || p.action === 'done') {
    if (typeof p.playerId !== 'string' || !p.playerId) return null;
    if (p.action === 'join' || p.action === 'done') {
      return { kind: 'game', game: 'truth-or-dare', action: p.action, playerId: p.playerId };
    }
    if (p.action === 'choose' && (p.choice === 'truth' || p.choice === 'dare')) {
      return { kind: 'game', game: 'truth-or-dare', action: p.action, playerId: p.playerId, choice: p.choice };
    }
    if (p.action === 'challenge' && typeof p.text === 'string' && p.text.trim()) {
      return { kind: 'game', game: 'truth-or-dare', action: p.action, playerId: p.playerId, text: p.text };
    }
    return null;
  }
  if (p.action === 'end') {
    return {
      kind: 'game',
      game: 'truth-or-dare',
      action: 'end',
      ...(typeof p.winnerId === 'string' ? { winnerId: p.winnerId } : {}),
    };
  }
  return null;
}

/** Sorted member ids — the deterministic-order requirement for the wheel. */
export function sortedMemberIds(ids: string[]): string[] {
  return [...ids].sort();
}
