/**
 * Raise the Gradle daemon's heap for the Android build.
 *
 * `:app:packageRelease` reads every file it zips into memory whole —
 * `zipflinger` calls `Files.readAllBytes` per entry — and on this app that
 * exceeded the 2 GB the Expo template gives the daemon:
 *
 *     Caused by: java.lang.OutOfMemoryError: Java heap space
 *       at com.android.zipflinger.BytesSource.<init>(BytesSource.java:49)
 *
 * The APK carries LiveKit, WebRTC, VisionCamera and Skia — tens of megabytes
 * of native libraries per ABI — plus the bundled typefaces and app icons, so
 * the packager is holding a lot at once. The runner has 16 GB; the default was
 * simply not sized for a binary this shape.
 *
 * A config plugin rather than a line in `android/gradle.properties`, because
 * `android/` is generated by prebuild and anything written there by hand is
 * gone on the next run. `expo-build-properties` has no option for this — its
 * Android surface covers SDK versions, Maven repos and packaging flags, not
 * the daemon's JVM — so this is the supported way to reach that file.
 */
const { withGradleProperties } = require('expo/config-plugins');

const KEY = 'org.gradle.jvmargs';

module.exports = function withGradleHeap(config, { jvmargs } = {}) {
  if (!jvmargs) throw new Error('with-gradle-heap: `jvmargs` is required');

  return withGradleProperties(config, (cfg) => {
    // Drop any existing declaration first. Gradle takes the last value for a
    // key, but leaving both in the file makes it read as though the template's
    // 2 GB is still in force, which is exactly the confusion this comment is
    // here to prevent.
    cfg.modResults = cfg.modResults.filter(
      (item) => !(item.type === 'property' && item.key === KEY),
    );
    cfg.modResults.push({ type: 'property', key: KEY, value: jvmargs });
    return cfg;
  });
};
