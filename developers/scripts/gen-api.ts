function responseText(description: string, pt: boolean): string {
  if (!pt) return description;
  const t = RESPONSES_PT[description];
  if (t === undefined) throw new Error(`No Portuguese for response: ${description}`);
  return t;
}

function deref(node: Any | undefined): Any | undefined {
  if (!node?.$ref) return node;
  const path = String(node.$ref).replace(/^#\//, '').split('/');
  return deref(path.reduce((o: Any, k) => o?.[k], spec));
}

function typeOf(schema: Any | undefined): string {
  const s = deref(schema);
  if (!s) return '';
  if (schema?.$ref) return String(schema.$ref).split('/').pop()!;
  if (s.type === 'array') return `${typeOf(s.items)}[]`;
  if (s.enum) return s.enum.map((v: string) => `\`${v}\``).join(' \\| ');
  if (s.oneOf) return s.oneOf.map(typeOf).join(' \\| ');
  return s.format ? `${s.type} (${s.format})` : s.type ?? 'object';
}

const cell = (v: unknown) => String(v ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

function render(lang: 'en' | 'pt'): string {
  const t = L[lang];
  const pt = lang === 'pt';
  const out: string[] = [
    '---',
    `title: ${t.title}`,
    'sidebar_position: 2',
    '---',
    '',
    '<!-- Generated by scripts/gen-api.ts from openapi/bot-api.yaml. Do not edit. -->',
    '',
    `# ${t.title}`,
    '',
    pt ? spec.info['x-description-pt'] : spec.info.description,
    '',
    `${t.intro} \`${spec.servers[0].url}\`. ${t.auth}`,
    '',
  ];
  const byTag = new Map<string, { method: string; path: string; op: Any }[]>();
  for (const [path, item] of Object.entries(spec.paths as Any)) {
    for (const [method, op] of Object.entries(item as Any)) {
      const tag = (op as Any).tags?.[0] ?? 'Other';
      if (!byTag.has(tag)) byTag.set(tag, []);
      byTag.get(tag)!.push({ method: method.toUpperCase(), path, op: op as Any });
    }
  }
  for (const [tag, ops] of byTag) {
    out.push(`## ${pt ? TAGS_PT[tag] ?? tag : tag}`, '');
    for (const { method, path, op } of ops) {
      out.push(`### \`${method} ${path}\``, '', `**${pt ? op['x-summary-pt'] ?? op.summary : op.summary}**`, '');
      const desc = pt ? op['x-description-pt'] ?? op.description : op.description;
      if (desc) out.push(desc, '');
      if (op['x-scope']) out.push(`${t.scope}: \`${op['x-scope']}\``, '');
      const params = (op.parameters ?? []).map(deref) as Any[];
      if (params.length) {
        out.push(`${t.params}:`, '', `| ${t.name} | ${t.in} | ${t.type} |`, '|---|---|---|');
        for (const p of params) out.push(`| \`${p.name}\` | ${p.in} | ${cell(typeOf(p.schema))}${p.required ? ` (${t.required})` : ''} |`);
        out.push('');
      }
      const body = deref(op.requestBody?.content?.['application/json']?.schema);
      if (body?.properties) {
        out.push(`${t.body}:`, '', `| ${t.name} | ${t.type} | ${t.notes} |`, '|---|---|---|');
        for (const [name, s] of Object.entries(body.properties as Any)) {
          const req = (body.required ?? []).includes(name) ? `${t.required}. ` : '';
          const prop = deref(s as Any) ?? {};
          const note = pt && prop.description ? prop['x-description-pt'] : prop.description;
          if (pt && prop.description && !note) throw new Error(`No x-description-pt for body field ${name} of ${method} ${path}`);
          out.push(`| \`${name}\` | ${cell(typeOf(s as Any))} | ${cell(req + (note ?? ''))} |`);
        }
        out.push('');
      }
      out.push(`${t.responses}:`, '');
      for (const [code, r] of Object.entries(op.responses as Any)) out.push(`- \`${code}\` ${responseText(deref(r as Any)?.description ?? '', pt)}`);
      out.push('');
    }
  }
  return out.join('\n');
}

function write(file: string, text: string) {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
}
write(join(root, 'docs/api/reference.md'), render('en'));
write(join(root, 'i18n/pt/docusaurus-plugin-content-docs/current/api/reference.md'), render('pt'));
